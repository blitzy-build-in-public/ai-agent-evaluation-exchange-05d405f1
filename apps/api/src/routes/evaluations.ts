/**
 * The demonstration evaluator's two contract rows and the single computation path the product is
 * built around: `POST /evaluations` (developer, owner of the candidate version) writes one
 * reproducible SGI report, and `GET /evaluations/{id}` (public) reads it back with its per-case
 * evidence.
 *
 * **This file owns the two rows and derives nothing they report.** It is the only writer of
 * `evaluation_reports` and `report_case_results` — through `@adem/sgi-core`'s `insertReport` — and
 * the only caller of the gate-evaluation fee `@adem/commerce-sim` records, and every value the
 * report states comes from a single domain call: the per-case results, the matched and total
 * counts, the critical failures, the failing case ids and the `PASS`/`FAIL` outcome come from
 * `scoreSubmission`, the label from `deriveReportLabel`, the rubric reference from `buildReport`,
 * the fee from `recordGateFeeCharge`. No arithmetic is written here and no threshold is restated:
 * the pass rule is read from the stored standard version's own criteria.
 *
 * **The steps run in one fixed order**, because that order decides which status a caller is
 * answered with: the write rate limit, the request schemas, the demo account (`401`), the role
 * (`403`), the candidate version read from this workspace's own `listing_versions` table (`404`),
 * the ownership check (`403`), the versioned criteria and the fixture case set (`404`, `400`), the
 * scoring, and then — inside one transaction — the label, the server-derived retest link, the
 * report with its evidence, the `retest_created` governance event the link is recorded in, the gate
 * fee and the audit event.
 *
 * **The `422` fires before anything is written.** A submission that records no output for a fixture
 * case is refused by the scorer as `incomplete_submission`, which maps to the contract's `422`, and
 * that refusal is raised before the report insert and before the fee, so a rejected submission
 * leaves zero new rows in `evaluation_reports`, `report_case_results` and `ledger_entries`.
 *
 * **Nothing is executed.** A candidate is declarative data — a case id and a recorded JSON value
 * per case — compared as canonical JSON by `@adem/sgi-core`. There is no `eval`, no `new Function`,
 * no dynamic import of submitted content and no sandbox on this path, and no field of the
 * submission body names a file, a command or an endpoint.
 *
 * **The retest link is the server's and never a client's.** The body carries no retest field, and
 * its `additionalProperties: false` is what the scope's request-body policy holds a submission to: a
 * field a client did add is refused with `400 validation_error` before this handler runs. The prior
 * report is derived here from the reports already stored for the submitted
 * candidate version and standard version, so a retest appends a report pointing at its predecessor
 * while the predecessor stays byte-identical, and the link is recorded in the append-only governance
 * log as a `retest_created` event beside the report it created.
 *
 * **What it never touches.** No statement here updates or deletes anything, and none carries a
 * replace-style conflict resolution, because `evaluation_reports` and `report_case_results` are
 * append-only — a change to a measurement is a new report. Nothing here reads `sponsored_slots`, and
 * the one commercial value it handles is the configured gate fee, which is recorded in the
 * gate-evaluation-fee ledger alone and is ineligible for a founder allocation; a report, its label
 * and its rubric reference are therefore byte-identical when sponsorship and fee data vary.
 *
 * **It holds no clock and no random source of its own.** The report's identifier and its creation
 * instant are generated by the writer at insert time and lie outside the compared payload, which is
 * what lets two runs of one submission compare byte for byte.
 */

