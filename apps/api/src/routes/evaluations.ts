/**
 * The slice of the folder's single `RouteContext` this group needs: the open database handle and
 * the resolved API configuration, both of which arrive by closure from the server factory rather
 * than through Fastify plugin options.
 *
 * `RouteContext` itself is declared once, in the sibling `./register-routes`, which registers this
 * group's routes and is written last in this folder because it imports all fourteen groups' values.
 * This file spells the members structurally instead of importing that type, so that this file and
 * the `apps/api` project compile on their own, before `./register-routes` exists; a `RouteContext`
 * carrying a `Database` and an `ApiConfig` is assignable to this shape, so the registrar's call site
 * is unaffected.
 *
 * The configuration is read for two values and no others: the resolved write rate-limit numbers
 * this group's write registers, and the resolved commerce configuration the fee writer is handed.
 * `apps/api/src/server.ts` passes the handle in, so this module opens no connection, reads no
 * environment variable and resolves no path.
 */
interface EvaluationRouteContext {
  /** The open database handle, whose pragmas and migrations the composition root already applied. */
  readonly database: Database;

  /** The resolved configuration: the write rate-limit bound and the commerce fee configuration. */
  readonly config: ApiConfig;
}

/**
 * The submission shape `scoreSubmission` accepts, taken from that function's own signature rather
 * than restated.
 *
 * The parameter type belongs to `@adem/sgi-fixtures`, which this workspace may not import: a
 * workspace is reached through its public entry and `apps/api` declares no dependency on the
 * fixture package, because the route reaches a case set through `@adem/sgi-core`'s
 * `getStandardCaseSet` and never through the loader. Reading the type off the function keeps this
 * file's contract with the domain exact — a member that function's parameter gains or narrows is a
 * compile error here — without an import the architecture forbids.
 */
type ScoringSubmission = Parameters<typeof scoreSubmission>[2];

/**
 * The recorded-outputs array of that submission. Spelled as its own alias because the one value this
 * file converts is a member of it: see {@link toScoringSubmission} on why the conversion is a type
 * assertion and not a rewrite.
 */
type ScoringRecordedOutputs = ScoringSubmission["recorded_outputs"];

/**
 * One `listing_versions` row together with the fact about its listing this route needs: who
 * published the version, and whether it was seeded as one of the fixture candidates.
 *
 * The two joined columns are aliased apart from the version's own, so one row carries both without a
 * collision and the select list below can be read against
 * `packages/shared/migrations/0002_listings_and_versions.sql` line by line.
 *
 * `is_fixture_candidate` is a plain `number` here because the column stores the integer 1 or 0:
 * better-sqlite3 refuses a JavaScript boolean binding, and the migration declares the pair in a
 * `CHECK`. It is narrowed to a boolean at the one place it is read, and it is the only input the
 * report's label rule reads.
 */
interface CandidateVersionRow {
  /** Primary key of the version row, which is the report's `candidate_version_id`. */
  readonly id: string;

  /** The listing the version belongs to. */
  readonly listing_id: string;

  /** `accounts.id` of the developer that published the listing, from the joined listing row. */
  readonly developer_account_id: string;

  /** 1 when the version was seeded as a fixture candidate, 0 otherwise. */
  readonly is_fixture_candidate: number;
}

/**
 * The one read this file performs against its own tables: the candidate version a submission names,
 * joined to the listing that owns it.
 *
 * Both tables belong to this workspace, which is why the ownership question is answered here and not
 * by `@adem/sgi-core`: that package owns `standards`, `standard_versions`, the reports and the
 * governance log, and it reads neither `listings` nor `listing_versions`. Asking it about a version's
 * owner would give it a second owner's table to read.
 *
 * The row comes back whole in one statement rather than in two, so a version row and its listing
 * cannot be observed in different states between the two lookups of one request.
 */
const SELECT_CANDIDATE_VERSION_SQL = `SELECT
  v.id AS id,
  v.listing_id AS listing_id,
  l.developer_account_id AS developer_account_id,
  v.is_fixture_candidate AS is_fixture_candidate
FROM listing_versions AS v
JOIN listings AS l ON l.id = v.listing_id
WHERE v.id = ?`;

/**
 * The candidate version a submission names, or `undefined` when no version carries that identifier.
 *
 * One exact-equality lookup on the table's primary key, and a statement of this file's own: this
 * workspace owns `listing_versions`, and the row is read here so that both the ownership check and
 * the report's label origin come from one read of one row. Nothing is cached between requests and
 * nothing is written: a hit and a miss both leave every row as it was.
 *
 * The statement is prepared per call because a prepared statement belongs to the connection that
 * made it, and this module owns no connection — the handle is the caller's, as ports and adapters
 * require. SQLite caches the compiled statement itself, so the per-call `prepare` allocates no plan
 * of its own.
 */
function readCandidateVersion(database: Database, id: string): CandidateVersionRow | undefined {
  return database.prepare<[string], CandidateVersionRow>(SELECT_CANDIDATE_VERSION_SQL).get(id);
}

/**
 * The standard version a submission names, resolved from either reference form the body's
 * `standard_version_id` may carry.
 *
 * The first probe is the domain's own form — the same value used as the standard reference and as
 * the version reference — which resolves the contract-facing label a report cites (`SGI-SO-1.0.0`)
 * and a standard's own code or identifier.
 *
 * The second probe covers the other form that field documents, a `standard_versions.id`. A version
 * row's identifier resolves no standard through the first probe, because a version's identifier is
 * neither a standard's code nor a standard's identifier; scoping the version probe to the release's
 * standard by that standard's own published code resolves it, and the code is read from the standard
 * definition in `@adem/sgi-core` rather than spelled here. Both forms resolve to the same record for
 * one version, so what a report states never depends on which form a client sent — and neither probe
 * computes a criterion, both reading the row and its criteria as the domain hands them back.
 *
 * A reference that resolves nothing is `null`, which the caller answers `404`. A reference that
 * resolves ambiguously, or a version whose persisted definition contradicts its row, refuses through
 * the domain's own errors and is mapped by the server's single error handler.
 */
function resolveStandardVersion(
  database: Database,
  reference: string,
): StandardVersionRecord | null {
  return (
    getStandardVersion(database, reference, reference) ??
    getStandardVersion(database, SGI_SO_1_0_0.code, reference)
  );
}

/**
 * The submission `scoreSubmission` scores, assembled from the request body.
 *
 * The four members are the ones that function's parameter declares, and two of them are stated here
 * rather than taken from the body. A submission recorded on disk names the pack file it was loaded
 * from, while a submission sent to this API has no file behind it, so the version it declares is the
 * only name its recording has and serves as both identifiers. And the standard version is stated as
 * the label the resolved criteria publish — never as the reference the body carried — because the
 * body may name that version either by its label or by its row identifier, while the scorer's own
 * drift check compares the submission's declared version against the version's label. Passing the
 * label through is a normalisation of one reference form into the other, not a derivation: it is the
 * label read from the row the criteria were resolved from, so both forms score the same submission.
 * The candidate version and the recorded outputs are the body's own values, handed on untouched, in
 * the order the client stated them.
 *
 * The one conversion is the recorded outputs' type, and it is an assertion rather than a rewrite:
 * every `output` of a parsed JSON request body is a JSON value by construction — the schema requires
 * the field and deliberately leaves its shape unconstrained, so that a well-formed recording of any
 * shape is scored rather than refused, and `@adem/shared` types it `unknown` for exactly that reason
 * while the fixture loader types it as the JSON value its own parse produced. No member is renamed,
 * reordered or inspected here, and nothing is decided: whether a value can be rendered as canonical
 * JSON is the canonicaliser's question, and it refuses what it cannot render.
 */
function toScoringSubmission(
  body: EvaluationSubmission,
  standardVersionLabel: string,
): ScoringSubmission {
  return {
    candidate_id: body.candidate_version_id,
    candidate_version_id: body.candidate_version_id,
    standard_version_id: standardVersionLabel,
    recorded_outputs: body.recorded_outputs as ScoringRecordedOutputs,
  };
}

/**
 * One report as the contract returns it, mapped from the domain's own record into the wire shape
 * `@adem/shared` declares.
 *
 * This file is the mapping layer between the two spellings, and no field-renaming helper exists
 * elsewhere: the domain's records are camelCase and the payload is snake_case, so the translation
 * lives at the one boundary that has both in scope, written out member by member so the
 * correspondence is readable in place.
 *
 * Nothing is derived, rounded or recomputed. The counts, the outcome, the label, the rubric
 * reference and the prior report all pass through as the evaluation and its writer recorded them,
 * and each per-case entry carries the two canonical JSON strings the comparison compared, so a
 * report a client renders states what was measured rather than a second computation of it. The
 * per-case results stay in the order the writer appends them in, which is the case set's own order,
 * and never a database order.
 *
 * The parameter is typed as the record `insertReport` writes, which the stored report read back out
 * of the database is assignable to: one mapping therefore serves both routes, so the report a
 * submission is answered with and the report the same identifier is later read from state the same
 * fields.
 */
function toEvaluationReportDetail(report: ReportRecord): EvaluationReportDetail {
  return {
    id: report.reportId,
    candidate_version_id: report.candidateVersionId,
    standard_version_id: report.standardVersionId,
    outcome: report.outcome,
    matched_count: report.matchedCount,
    total_count: report.totalCount,
    critical_failures: report.criticalFailures,
    label: report.label,
    rubric_reference: report.rubricReference,
    prior_report_id: report.priorReportId,
    created_at: report.createdAt,
    case_results: report.caseResults.map((caseResult) => ({
      case_id: caseResult.caseId,
      severity: caseResult.severity,
      expected: caseResult.expectedJson,
      actual: caseResult.actualJson,
      match: caseResult.match,
    })),
  };
}

/**
 * Registers this group's two routes — the deterministic evaluation and its report read — on the
 * instance it is handed.
 *
 * The paths are prefix-relative: the versioned prefix — `API_PREFIX`, declared once in the sibling
 * `./register-routes` — is applied exactly once, by `./register-routes`, which calls this function with
 * its encapsulated scope. That literal appears nowhere in this file and must not: a group that spelled it
 * would be the second place the prefix is decided. The two routes are registered in contract-table order.
 *
 * The write carries two schema sections and one option. `demoAccountHeaderSchema` is what makes an
 * absent or empty `X-Demo-Account` a validation failure at the edge, which the server's single error
 * handler answers `401 unauthorized` for this header, and `evaluationSubmissionBodySchema` validates
 * the declarative submission, whose `additionalProperties: false` is what the scope's request-body
 * policy holds a client to, refusing a client-supplied retest field with `400 validation_error`
 * before this handler runs. The rate-limit option is the contract's write limit, read
 * from the resolved configuration rather than restated, and it is attached to this route alone: the
 * plugin is registered without a global default, so a route that wants the limit names it and every
 * read stays unlimited.
 *
 * No failure is caught here. The server's single error handler owns `{ error: { code, message } }`
 * and maps a domain refusal by its stable code, so a handler-local error body would be a second
 * answer to one question; the two statuses this group raises itself are raised as `ApiError`s from
 * the shared envelope.
 */
export function registerEvaluationRoutes(
  app: FastifyInstance,
  context: EvaluationRouteContext,
): void {
  const writeRouteOptions = {
    schema: { ...demoAccountHeaderSchema, ...evaluationSubmissionBodySchema },
    config: {
      rateLimit: {
        max: context.config.writeRateLimit.max,
        timeWindow: context.config.writeRateLimit.timeWindow,
      },
    },
  };

  app.post<{ Body: EvaluationSubmission }>(
    "/evaluations",
    writeRouteOptions,
    (request, reply) => {
      // Step 1 — identity, and the only two statuses it produces: `401` when the header is absent or
      // names no seeded account, `403` when the resolved account is not a developer. This route
      // resolves the account before it reads anything, so a caller that cannot write is told so
      // without being told whether the resource it named exists.
      const account = requireRole(
        resolveDemoAccount(
          context.database,
          request.headers[DEMO_ACCOUNT_HEADER.toLowerCase()],
        ),
        "developer",
      );

      const body = request.body;

      // Step 2 — the candidate version, from this workspace's own table: `404` when no version
      // carries the identifier. The row supplies the origin the report's label is derived from.
      const candidateVersion = readCandidateVersion(context.database, body.candidate_version_id);

      if (candidateVersion === undefined) {
        throw ApiError.notFound(
          "No listing version carries the candidate version this submission names.",
        );
      }

      // Step 3 — ownership: the row's `403`. A resolved developer that does not own the listing this
      // version belongs to may not have it measured under its own account, and the check compares
      // identifiers only, so it discloses nothing about the version or its owner.
      if (candidateVersion.developer_account_id !== account.id) {
        throw ApiError.forbidden(
          "This submission names a listing version published by another developer.",
        );
      }

      // Step 4 — the versioned criteria and the case set, from one resolution. `404` when no published
      // standard version matches, `400` when the standard's definition and its fixture set have
      // drifted apart; both are the domain's refusals, mapped by the error handler from their own
      // codes. The resolution happens here and once: the record it returns names the criteria the
      // scorer reads and is handed to the case-set loader below, so the row behind it is neither read
      // nor re-parsed a second time in this request.
      const standardVersion = resolveStandardVersion(
        context.database,
        body.standard_version_id,
      );

      if (standardVersion === null) {
        throw ApiError.notFound(
          "No standard version published here matches the standard version this submission names.",
        );
      }

      const caseSet = getStandardCaseSet(context.database, standardVersion);

      // Step 5 — scoring. The pass rule is applied inside `scoreSubmission`, which reads the
      // thresholds from the versioned criteria resolved above; its refusals are the contract's:
      // `incomplete_submission` (a fixture case with no recorded output) is `422`, `unknown_case` and
      // `duplicate_case` are `400`, and a recorded output holding a number JSON cannot represent —
      // the `1e999` a client can send, because the submission schema leaves `output` unconstrained —
      // is `unrenderable_value`, also `400`. They are raised here, before any write, so a refused
      // submission leaves the report, evidence and ledger tables exactly as they were. Nothing
      // submitted is executed on this path.
      const scored = scoreSubmission(
        standardVersion.definition,
        caseSet,
        toScoringSubmission(body, standardVersion.definition.versionLabel),
      );

      // Step 6 — the label, decided by the domain from the version's origin and nothing else. It is
      // total over every report: a version seeded as a fixture candidate is `SAMPLE` and every other
      // version is `VERIFIED-IN-DEMO`, on a `FAIL` exactly as on a `PASS`. A `FAIL` report carries
      // the same label and no badge, and the badge is the report page's rule rather than this one's.
      const label = deriveReportLabel(
        candidateVersion.is_fixture_candidate === 1,
        scored.outcome,
      );

      // Steps 7 to 10 — one act. The report with its per-case evidence, the retest's governance event,
      // the gate fee and the audit event are written inside one enclosing transaction: a completed
      // evaluation can therefore never leave a report without its fee record or without the audit row
      // that says who wrote it, and a failure anywhere in them rolls the whole attempt back.
      // `insertReport` opens its own transaction for the report and its evidence; better-sqlite3 nests
      // it as a savepoint, so the two are one act rather than two. `appendEvent` and `appendAuditEvent`
      // open none of their own, which is why they are called inside this one.
      const report = context.database.transaction((): ReportRecord => {
        // A retest link, derived from the reports already stored for this candidate version and this
        // standard version and never accepted from the client. `null` when that version has no report
        // yet; the newest report's identifier otherwise. The link is read inside the same transaction
        // that appends the report it points away from, so the predecessor a report cites cannot
        // change between the read and the write. The version is the record resolved in step 4 and not
        // its label again: a label would have to be resolved to the row identifier the column stores,
        // which would read and re-parse the same row this request already holds.
        const priorReportId = findLatestReportId(
          context.database,
          body.candidate_version_id,
          standardVersion,
        );

        const record = buildReport(scored, {
          candidateVersionId: body.candidate_version_id,
          standardVersionId: scored.standardVersionId,
          label,
          priorReportId,
        });

        // The version resolved in step 4 is handed in, so the report is stored against the row that
        // request already resolved rather than against a second resolution of the same label: the
        // function stores that record's identifier after checking it is the label this report cites.
        insertReport(context.database, record, standardVersion);

        // The retest is recorded where its link is derived, in the transaction that appends the report
        // it points away from: the append-only log is the record of what was decided, and a report
        // linking to a predecessor is exactly that decision. A first submission for this candidate
        // version and standard version has no predecessor — `priorReportId` is `null` — so it appends
        // nothing new and the log gains one event per retest rather than one per submission. No reason
        // is passed: a retest decides by what it points at, and the report's own audit row records the
        // write beside it.
        if (priorReportId !== null) {
          appendEvent(context.database, {
            subjectType: "evaluation_report",
            subjectId: record.reportId,
            eventType: "retest_created",
            actorAccountId: account.id,
            payload: {
              reportId: record.reportId,
              priorReportId,
              candidateVersionId: record.candidateVersionId,
              standardVersionId: record.standardVersionId,
            },
          });
        }

        // The flat fictional gate fee, once per completed evaluation and whether the outcome is
        // `PASS` or `FAIL`. The call is handed the completed report's identifier and the resolved
        // configuration and nothing else, so the fee cannot vary with what the evaluation found; it
        // is recorded in the gate-evaluation-fee ledger alone, is ineligible for a founder
        // allocation, and appends nothing at all when the configured fee is zero.
        recordGateFeeCharge(context.database, {
          reportId: record.reportId,
          config: context.config.commerce,
        });

        appendAuditEvent(context.database, {
          actorAccountId: account.id,
          action: "evaluation.created",
          resourceType: "evaluation_report",
          resourceId: record.reportId,
          statusCode: 201,
        });

        return record;
      })();

      // The report a client renders is the record that was just written, so it states the label, the
      // rubric reference and the retest link the same read would return.
      return reply.code(201).send(toEvaluationReportDetail(report));
    },
  );

  app.get<{ Params: { id: string } }>(
    "/evaluations/:id",
    { schema: evaluationIdParamsSchema },
    (request, reply) => {
      // A public read: it resolves no identity at all, so a garbage header, a wrong-role header and
      // an absent header are answered alike, and no demo account is required to read a report.
      const report = getReport(context.database, request.params.id);

      // An identifier that matches nothing is `404` rather than an empty report: a stored report is
      // either there or it is not, and the read itself refuses nothing but this.
      if (report === null) {
        throw ApiError.notFound("No evaluation report carries this identifier.");
      }

      // The same mapping the write answers with. The evidence comes back in the order it was
      // written in — the case set's own order — so two reads of one report, and a read of a report
      // just written, answer byte-identical bodies.
      return reply.code(200).send(toEvaluationReportDetail(report));
    },
  );
}

